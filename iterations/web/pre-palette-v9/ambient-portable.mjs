// The portable shows an exact copy of the ambient-device-visuals sketch. ambient/sketch.js is the
// ambient file byte for byte; ambient/sketch-portable.js is generated from it by applying only the
// patches below (run `npm run sync-ambient` after the ambient sketch changes).
export const PATCHES=Object.freeze([
 // The round 480 × 480 display shows a square lamp. Width stays 600 so every px-tuned ambient value
 // (drop sizes, speeds, flow) keeps the same proportions to the screen; the canvas is drawn at 480.
 ['const CANVAS_H = 1024;','const CANVAS_H = 600; // portable: square lamp, displayed at 480 × 480'],
 // One population only: the teal wax (ambient population index 1); the green and blue are removed.
 ['const POP_COUNT = 3;','const POP_COUNT = 1; // portable: teal only'],
 ["const POP_COLORS = Object.freeze(['#8DD644', '#00E2B7', '#009AE2']);","const POP_COLORS = Object.freeze(['#00E2B7']); // portable: teal only"],
 // Same-colour fusing made adjustable for the Merging slider (app.js); values stay the ambient ones
 // until the slider moves off its middle.
 ['const DRAIN_FRAMES =','let DRAIN_FRAMES ='],
 ['const SEPARATING_SPEED =','let SEPARATING_SPEED ='],
 ['const FUSE_REACH =','let FUSE_REACH ='],
 // Portable background (user's standing choice); ambient uses #2F302F.
 ["background('#2F302F');","background('#594F47');"]
]);
export const HEADER='// GENERATED by scripts/sync-ambient.mjs from ambient/sketch.js (ambient-device-visuals) with the\n// portable patches in ambient-portable.mjs. Do not edit; edit the patches or re-sync instead.\n';
export function patchSketch(source){
 let out=source;
 for(const [from,to] of PATCHES){
  const count=out.split(from).length-1;
  if(count!==1)throw new Error(`ambient patch expected once, found ${count}: ${from}`);
  out=out.replace(from,to);
 }
 return HEADER+out;
}
